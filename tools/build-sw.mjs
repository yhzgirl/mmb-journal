// Writes sw.js with the list of app files and a version made from their contents,
// so the phone picks up every change. Run after editing any app file:
//   node tools/build-sw.mjs
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const include = ['index.html', 'decrypt.html', 'manifest.json', 'styles', 'src', 'icons', 'fonts'];
const skip = /(LICENSE|\.md|\.txt)$/;
const files = [];
const walk = p => statSync(p).isDirectory() ? readdirSync(p).sort().forEach(f => walk(join(p, f))) : files.push(p);
include.forEach(p => walk(join(root, p)));
const shell = files.map(f => relative(root, f).split('\\').join('/')).filter(f => !skip.test(f) && !f.startsWith('.'));
const hash = createHash('sha256');
for (const f of shell) hash.update(f).update(readFileSync(join(root, f)));
const version = hash.digest('hex').slice(0, 10);

writeFileSync(join(root, 'sw.js'), `// Generated by tools/build-sw.mjs. Don't edit by hand.
// Opens straight from the copy saved on the phone (fast, works offline), then
// fetches fresh copies in the background so updates show on the next open.
const CACHE = 'mmb-journal-${version}';
const SHELL = ${JSON.stringify(['./', ...shell], null, 2)};

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(SHELL)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('mmb-journal-') && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
const keyFor = url => (url.pathname.endsWith('/') ? url.pathname + 'index.html' : url.pathname);
self.addEventListener('fetch', e => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== self.location.origin) return;
  const key = keyFor(url);
  e.respondWith(caches.open(CACHE).then(async c => {
    const saved = await c.match(key);
    const fresh = fetch(new Request(url.origin + url.pathname, { cache: 'no-cache', credentials: 'same-origin' }))
      .then(res => { if (res.ok) c.put(key, res.clone()); return res; });
    if (saved) { e.waitUntil(fresh.catch(() => {})); return saved; }
    return fresh.catch(() => c.match(keyFor(new URL('./', self.location))));
  }));
});
`);
console.log(`sw.js: ${shell.length + 1} files, version ${version}`);
